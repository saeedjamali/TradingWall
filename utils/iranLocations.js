// تابع برای دریافت شهرهای یک استان با اولویت شهرهای بزرگ
export function getCitiesByProvince(province) {
  const provinceCities = cities[province] || []
  
  // شهرهای بزرگ در این استان
  const majorInProvince = provinceCities.filter(city => majorCities.includes(city))
  
  // بقیه شهرها
  const otherCities = provinceCities.filter(city => !majorCities.includes(city))
  
  // ترکیب: شهرهای بزرگ اول، بعد بقیه
  return [...majorInProvince, ...otherCities]
}
